#!/usr/bin/env python3
"""Build the Desktop plugin and the web-dashboard bundle from ui/core.js.

Both outputs are committed (Desktop loads disk plugins uncompiled, the dashboard loads a pre-built IIFE), and
`tests/test_ui_build.py` fails if they drift from the source. Run: python scripts/build_ui.py
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CORE = (ROOT / "ui" / "core.js").read_text()
DESKTOP_OUT = ROOT / "nightshift" / "desktop" / "plugin.js"
DASHBOARD_OUT = ROOT / "nightshift" / "dashboard" / "dist" / "index.js"

BANNER = "/* GENERATED by scripts/build_ui.py from ui/core.js. Edit the source, then rebuild. */\n"

DESKTOP = (
    BANNER
    + """/**
 * Nightshift for Hermes Desktop: a live pane for watched training runs and a status-bar chip.
 * Disk plugins load uncompiled: no JSX; imports limited to @hermes/plugin-sdk, react, react/jsx-runtime.
 * Data comes from the plugin's backend routes (dashboard/plugin_api.py) through ctx.rest.
 */

import { STATUSBAR_AREAS, Tip, host } from '@hermes/plugin-sdk'
import { jsx } from 'react/jsx-runtime'
import { useEffect, useState } from 'react'

function h(type, props, ...children) {
  const { key, ...rest } = props || {}
  const kids = children.filter(c => c !== null && c !== undefined && c !== false)
  const all = kids.length === 0 ? undefined : kids.length === 1 ? kids[0] : kids
  return jsx(type, all === undefined ? rest : { ...rest, children: all }, key)
}

const THEME = {
  text: 'var(--ui-text-primary)',
  muted: 'var(--ui-text-tertiary)',
  border: 'var(--ui-stroke-secondary)',
  surface: 'var(--ui-bg-card)',
  chartBg: 'var(--ui-bg-tertiary)',
  accent: 'var(--ui-accent)',
  onAccent: 'var(--ui-bg-primary)',
  good: 'var(--ui-green)',
  warn: 'var(--ui-yellow)',
  bad: 'var(--ui-red)',
  val: 'var(--ui-green)',
  series1: 'var(--ui-accent)',
  series2: 'var(--ui-cyan)',
  series3: 'var(--ui-blue)',
  series4: 'var(--ui-purple)'
}

"""
    + CORE
    + """
export default {
  id: 'nightshift',
  name: 'Nightshift',
  register(ctx) {
    const ui = makeNightshiftUI({
      h,
      useState,
      useEffect,
      theme: THEME,
      api: {
        get: path => ctx.rest(path),
        post: path => ctx.rest(path, { method: 'POST' })
      },
      onNewAlerts: alerts => {
        for (const a of alerts.slice(0, 3)) {
          const body = a.message
          ctx.os.notify({ title: `Nightshift: ${a.kind.replace('_', ' ')}`, body })
          host.notify({ kind: 'error', message: `Nightshift: ${body}` })
        }
      }
    })

    ctx.register({
      id: 'pane',
      area: 'panes',
      title: 'Nightshift',
      data: { placement: 'right', width: '360px' },
      render: () => jsx(ui.Pane, {})
    })

    function ChipView() {
      const chip = ui.Chip()
      return jsx(Tip, {
        label: chip.label,
        children: jsx('span', {
          className: 'inline-flex h-full items-center gap-1 px-1.5 text-[0.6875rem]',
          style: { color: chip.color, fontVariantNumeric: 'tabular-nums' },
          children: chip.text
        })
      })
    }

    ctx.register({ id: 'chip', area: STATUSBAR_AREAS.right, order: 125, render: () => jsx(ChipView, {}) })
  }
}
"""
)

DASHBOARD = (
    BANNER
    + """/* Nightshift web-dashboard tab: a pre-built IIFE. React and fetchJSON come from the host SDK. */
(function () {
  var SDK = window.__HERMES_PLUGIN_SDK__
  var React = SDK.React
  var THEME = {
    text: 'var(--color-card-foreground)',
    muted: 'var(--color-muted-foreground)',
    border: 'var(--color-border)',
    surface: 'var(--color-card)',
    chartBg: 'var(--color-muted)',
    accent: 'var(--color-primary)',
    onAccent: 'var(--color-primary-foreground)',
    good: '#4fb477',
    warn: '#e0a84a',
    bad: '#e5566b',
    val: '#9ece6a',
    series1: '#7aa2f7',
    series2: '#7dcfff',
    series3: '#73daca',
    series4: '#bb9af7'
  }

"""
    + CORE
    + """
  var ui = makeNightshiftUI({
    h: React.createElement,
    useState: React.useState,
    useEffect: React.useEffect,
    theme: THEME,
    api: {
      get: function (path) { return SDK.fetchJSON('/api/plugins/nightshift' + path) },
      post: function (path) { return SDK.fetchJSON('/api/plugins/nightshift' + path, { method: 'POST' }) }
    }
  })

  function Tab() {
    return React.createElement('div', { style: { maxWidth: 760, margin: '0 auto', height: '100%' } },
      React.createElement(ui.Pane, null))
  }

  window.__HERMES_PLUGINS__.register('nightshift', Tab)
})()
"""
)


def main(check: bool = False) -> int:
    outputs = {DESKTOP_OUT: DESKTOP, DASHBOARD_OUT: DASHBOARD}
    stale = [p for p, text in outputs.items() if not p.exists() or p.read_text() != text]
    if check:
        for p in stale:
            print(f"stale: {p.relative_to(ROOT)} (run python scripts/build_ui.py)")
        return 1 if stale else 0
    for p, text in outputs.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text)
    print(f"built {len(outputs)} files")
    return 0


if __name__ == "__main__":
    sys.exit(main(check="--check" in sys.argv))
